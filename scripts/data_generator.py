"""
Synthetic Data Generator for LineageIQ
=============================================

Generates a realistic e-commerce data warehouse with:
  - 25 tables across 4 layers (raw, staging, curated, reporting)
  - Columns with data types and natural-language descriptions
  - 15 ETL jobs that define lineage (reads from → writes to)

The generated data represents a fictional e-commerce company called "ShopStream"
that processes orders, manages customers, handles payments, and tracks shipments.

Output:
  - data/synthetic/tables.json      → table definitions with descriptions
  - data/synthetic/columns.json     → column definitions with descriptions
  - data/synthetic/jobs.json        → ETL job definitions
  - data/synthetic/lineage_edges.json → which jobs read/write which tables

Usage:
  python scripts/data_generator.py

Why synthetic data?
  We don't need (and shouldn't use) real company data. This script generates
  a reproducible dataset that mirrors a real data warehouse closely enough
  to demonstrate the lineage system. Having the generator in the repo also
  shows engineering care — anyone can reproduce the demo.
"""

