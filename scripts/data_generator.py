# Create realistic job run history — some succeed, some fail.
# This data will be used later for "why did X fail?" questions.

def generate_job_runs(jobs, num_days=7):
    """Generate synthetic job run history for the past N days."""
    runs = []
    base_time = datetime(2026, 8, 23, 0, 0, 0)
    random.seed(42)  # Reproducible

    for day_offset in range(num_days):
        run_date = base_time - timedelta(days=day_offset)
        for job in jobs:
            # Parse schedule to determine how many times per day
            # Simplified: just run each job 1-3 times per day
            num_runs = 1 if job["schedule"].startswith("0") else random.randint(1, 3)

            for run_idx in range(num_runs):
                run_time = run_date + timedelta(
                    hours=random.randint(0, 23),
                    minutes=random.randint(0, 59),
                )

                # 90% success rate, 10% failure
                if random.random() < 0.10:
                    status = "failed"
                    error_messages = [
                        "Connection timeout to source database after 30s",
                        "Schema mismatch: column 'amount' expected DECIMAL but got STRING",
                        "Out of memory: job exceeded 8GB heap limit",
                        "Duplicate key violation on primary key constraint",
                        "Source API returned HTTP 503 Service Unavailable",
                        "Data quality check failed: null rate for order_id exceeded 5% threshold",
                        "Partition not found: source table partition for date not available yet",
                    ]
                    error = random.choice(error_messages)
                    duration_seconds = random.randint(5, 60)
                else:
                    status = "success"
                    error = None
                    duration_seconds = random.randint(30, 600)

                runs.append({
                    "job_name": job["name"],
                    "run_id": f"{job['name']}_{run_date.strftime('%Y%m%d')}_{run_idx}",
                    "started_at": run_time.isoformat(),
                    "duration_seconds": duration_seconds,
                    "status": status,
                    "error_message": error,
                    "records_processed": random.randint(100, 50000) if status == "success" else 0,
                })

    return runs


